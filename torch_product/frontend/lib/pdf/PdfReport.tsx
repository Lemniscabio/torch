type Props = { inputs: ProcessInputs; results: PartialAssessmentResult };

function fmt(n: number | undefined, digits = 2, unit = '') {
  if (n === undefined || !Number.isFinite(n)) return '—';
  return `${n.toFixed(digits)}${unit ? ` ${unit}` : ''}`;
}

function PageFrame({ children }: { children: React.ReactNode }) {
  const date = new Date().toISOString().slice(0, 10);
  return (
    <Page size="A4" style={s.page}>
      <View style={s.header}>
        <Text style={s.brand}>LEMNISCA · TORCH</Text>
        <Text style={s.meta}>Scale-up risk assessment · {date}</Text>
      </View>
      {children}
      <Text style={s.footer} fixed>
        Generated by Lemnisca Torch. Predictions are bounded by empirical correlations (±30–40% on kLa) and do not replace pilot experimentation.
      </Text>
    </Page>
  );
}

function Badge({ score }: { score: RiskScore }) {
  return (
    <Text style={[s.badge, { color: RISK_HEX[score], borderWidth: 1, borderColor: RISK_HEX[score], borderStyle: 'solid' }]}>
      {RISK_LABEL[score]}
    </Text>
  );
}


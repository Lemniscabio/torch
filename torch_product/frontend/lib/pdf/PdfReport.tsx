// ─── Page 4: Reliability Statement ───────────────────────────────────────────

function Reliability({ inputs, results }: Props) {
  const ourMeasured = inputs.our_mode === 'measured';
  const provenance = [
    { label: 'Organism + species', value: 'User-provided' },
    { label: 'Scale (lab / target)', value: 'User-provided' },
    { label: 'Geometry (H/D, D/T, impeller)', value: 'User-provided with sensible defaults' },
    { label: 'Operating (RPM, VVM, DO)', value: 'User-provided with defaults where omitted' },
    { label: 'OUR (peak)', value: ourMeasured ? 'User-measured (high confidence)' : 'Estimated from literature kinetics' },
    { label: 'Temperature + cooling water', value: 'User-provided' },
  ];

  const assumptions = [
    'kLa estimated via the van\'t Riet ensemble for coalescing/non-coalescing media; ±30–40% intrinsic uncertainty.',
    inputs.impeller_type === 'unknown'
      ? 'Unknown impeller type treated as Rushton geometry — replace with actual type for sharper power and shear estimates.'
      : 'Mixing time blended across Ruszkowski, Cooke, and Grenville-Nienow ensembles.',
    ourMeasured
      ? 'OUR is user-measured; downstream margins inherit this directly.'
      : 'OUR estimated from biomass + species — a measured value would tighten every domain except shear.',
  ];

  const recommendation = ourMeasured
    ? 'Pilot kLa measurement at intermediate volume to validate the scale-up envelope.'
    : 'A direct OUR measurement at peak biomass is the single highest-leverage measurement to upgrade this report.';

  return (
    <PageFrame>
      <Text style={s.sectionTitle}>Reliability Statement</Text>

      <Text style={s.subTitle}>Input provenance</Text>
      <View style={s.paramBox}>
        {provenance.map((p) => (
          <View key={p.label} style={s.paramRow}>
            <Text>{p.label}</Text>
            <Text style={s.monoValue}>{p.value}</Text>
          </View>
        ))}
      </View>

      <Text style={s.subTitle}>Highest-impact assumptions</Text>
      {assumptions.map((a, i) => (
        <View key={i} style={{ flexDirection: 'row', marginBottom: 4 }}>
          <Text style={{ width: 16, color: TEAL, fontWeight: 700 }}>{i + 1}.</Text>
          <Text style={[s.paragraph, { flex: 1 }]}>{a}</Text>
        </View>
      ))}

      <Text style={s.subTitle}>Most valuable additional measurement</Text>
      <Text style={s.paragraph}>{recommendation}</Text>

      <View style={s.scopeBox}>
        <Text style={{ fontSize: 8, fontWeight: 700, color: TEAL, marginBottom: 3 }}>SCOPE LIMITATIONS</Text>
        <Text style={s.paragraph}>
          This assessment is based on empirical correlations with ±30–40% uncertainty on kLa and ±15–20% on heat transfer. It does not predict yield, product titer, or replace pilot experimentation. Risk categories indicate the magnitude of attention each domain needs, not absolute pass/fail.
        </Text>
      </View>

      <View style={{ marginTop: 16, paddingTop: 8, borderTopWidth: 0.5, borderTopColor: RULE, borderTopStyle: 'solid' }}>
        <Text style={s.small}>
          Inputs: {speciesLabel(inputs.organism_species)} · {inputs.process_type.replace('_', '-')} · {inputs.v_lab} L → {inputs.v_target} L · {ourMeasured ? `measured OUR ${fmt(inputs.our_measured, 0, 'mmol/L/h')}` : 'estimated OUR'}
        </Text>
      </View>
    </PageFrame>
  );
}

